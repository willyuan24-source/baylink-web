import { mkdir, readdir, rm, writeFile } from 'node:fs/promises';
import { gzipSync } from 'node:zlib';
import { allDetailRecords } from '../src/features/detail/build-detail';
import type { DetailBucket, DetailRecord } from '../src/features/detail/detail-record';
import { DETAIL_BUCKET_COUNT, detailBucket } from '../src/lib/english-loading';
import aliases from '../src/data/event-id-aliases.json';

/**
 * Event, offer and opening detail records (ENGSEC-01, RC-33), in DETAIL_BUCKET_COUNT hashed buckets: a detail route loads
 * the one bucket its URL hashes to (~20 listings) instead of importing the whole content corpus. The records come from
 * the same catalogs as the prerendered page (src/features/detail/build-detail.ts). Old event ids that now redirect to a
 * merged listing (event-id-aliases.json) are written under their own key too, so a shared old link still resolves.
 * Deterministic: no dates of the run. Run with the home catalog (`npm run generate:home`: prebuild and pretest).
 */
const SAFE_ID = /^[A-Za-z0-9][A-Za-z0-9_-]{0,159}$/u;
const directory = 'src/data/generated/details';

const records = allDetailRecords();
const buckets: DetailBucket[] = [];
const bucketOf = (key: string) => { const [kind, id] = key.split(':') as ['event' | 'offer' | 'opening', string]; return Number(detailBucket(kind, id)); };
for (let index = 0; index < DETAIL_BUCKET_COUNT; index += 1) buckets.push({ events: {}, records: {} });
const add = (key: string, record: DetailRecord) => {
  const id = key.slice(key.indexOf(':') + 1);
  if (!SAFE_ID.test(id)) throw new Error(`Unsafe detail id: ${key}`);
  const bucket = buckets[bucketOf(key)];
  // Each rail event is stored once per bucket; the record keeps its ids in order.
  for (const event of record.rail) bucket.events[event.id] = event;
  bucket.records[key] = { ...record, rail: record.rail.map(event => event.id) };
};
for (const [key, record] of [...records].sort(([a], [b]) => a.localeCompare(b))) add(key, record);
for (const [alias, canonical] of Object.entries(aliases as Record<string, string>).sort(([a], [b]) => a.localeCompare(b))) {
  const record = records.get(`event:${canonical}`);
  if (record) add(`event:${alias}`, record);
}

await mkdir(directory, { recursive: true });
for (const file of await readdir(directory)) if (/^bucket-\d{2}\.json$/u.test(file)) await rm(`${directory}/${file}`);
const sizes: number[] = [];
for (const [index, bucket] of buckets.entries()) {
  const sortedEvents = Object.fromEntries(Object.entries(bucket.events).sort(([a], [b]) => a.localeCompare(b)));
  const serialized = JSON.stringify({ events: sortedEvents, records: bucket.records });
  sizes.push(gzipSync(serialized).length);
  await writeFile(`${directory}/bucket-${String(index).padStart(2, '0')}.json`, serialized);
}
const lines = buckets.map((_, index) => `  ${JSON.stringify(String(index).padStart(2, '0'))}: () => import(${JSON.stringify(`./details/bucket-${String(index).padStart(2, '0')}.json`)}),`);
await writeFile('src/data/generated/detail-loaders.ts', `// Generated by scripts/generate-detail-records.ts: one loader per detail bucket (lib/english-loading.ts detailBucket).\nexport const detailLoaders: Record<string, () => Promise<unknown>> = {\n${lines.join('\n')}\n};\n`);
const kib = (bytes: number) => (bytes / 1024).toFixed(1);
console.log(`Detail records: ${records.size} listings in ${DETAIL_BUCKET_COUNT} buckets; gzip per bucket ${kib(Math.min(...sizes))}–${kib(Math.max(...sizes))} KiB (mean ${kib(sizes.reduce((a, b) => a + b, 0) / sizes.length)}).`);
