/** Ground (world y) under a LOCAL point of the island (bilinear; 0 = the water line off the grid). */
export function alcaGround(lx: number, lz: number): number {
  const { x0, z0, step, cols, rows } = ALCA_GRID;
  const fx = (lx - x0) / step, fz = (lz - z0) / step;
  if (fx < 0 || fz < 0 || fx > cols - 1 || fz > rows - 1 || Y.length < cols * rows) return 0;
  const i = Math.min(cols - 2, Math.floor(fx)), j = Math.min(rows - 2, Math.floor(fz)), u = fx - i, v = fz - j;
  const at = (a: number, b: number) => Y[b * cols + a];
  return (at(i, j) * (1 - u) + at(i + 1, j) * u) * (1 - v) + (at(i, j + 1) * (1 - u) + at(i + 1, j + 1) * u) * v;
}

/** The lowest / highest ground over a LOCAL rectangle (centre, half extents, yaw), sampled every 0.5 u. */
export function alcaGroundSpan(cx: number, cz: number, hx: number, hz: number, ry = 0): { lo: number; hi: number } {
  const c = Math.cos(ry), s = Math.sin(ry);
  let lo = Infinity, hi = -Infinity;
  for (let a = -hx; a <= hx + 1e-6; a += Math.max(0.25, hx / 4)) for (let b = -hz; b <= hz + 1e-6; b += Math.max(0.25, hz / 4)) {
    const y = alcaGround(cx + a * c + b * s, cz - a * s + b * c);
    lo = Math.min(lo, y); hi = Math.max(hi, y);
  }
  return { lo, hi };
}

