export interface CornerMeshes { toy: THREE.Mesh | null; signs: THREE.Mesh | null; triangles: number; plaques: number }

/** Build the corner's two meshes (LOCAL frame of its site) for the windows `active`, the site mounted at `baseY`. */
export function buildCornerMeshes(def: CornerDef, baseY: number, active: ReadonlySet<string>): CornerMeshes {
  const ground = cornerGround(def, baseY);
  let triangles = 0, plaques = 0;
  const b = new TypedBatch(4096);
  def.build(b, ground, active);
  let toy: THREE.Mesh | null = null;
  if (b.vertexCount) {
    const a = b.toArrays();
    for (let i = 0; i < a.vertexCount; i++) a.info[i * 4 + 1] += baseY;
    toy = new THREE.Mesh(TypedBatch.toGeometry(a), TOY);
    toy.name = `sf:${def.site}:corner-toy`;
    toy.castShadow = false;
    toy.receiveShadow = true;
    toy.matrixAutoUpdate = false;
    triangles += a.indexCount / 3;
  }
  const sb = new SignBatch();
  for (const s of def.signs(ground, active)) sb.plaque(s.id, s.x, s.y, s.z, s.ry, s.w);
  let signs: THREE.Mesh | null = null;
  if (sb.count) {
    signs = new THREE.Mesh(sb.build(), signsMaterial());
    signs.name = `sf:${def.site}:corner-signs`;
    signs.castShadow = false;
    signs.receiveShadow = true;
    signs.matrixAutoUpdate = false;
    plaques = sb.count;
    triangles += sb.count * 2;
  }
  return { toy, signs, triangles, plaques };
}

/** What a mounted corner holds (tests and QA read it through `cornerState`). */
export interface CornerMounted { def: CornerDef; active: Set<string>; meshes: CornerMeshes; lod: THREE.LOD; crowds: string[]; soft: Obstacle[] }
const mounted = new Map<string, CornerMounted>();
/** The corners mounted now (QA: `window` console, tests). */
export function cornerState(): ReadonlyMap<string, CornerMounted> { return mounted; }

function disposeMeshes(m: CornerMeshes) { m.toy?.geometry.dispose(); m.signs?.geometry.dispose(); }

/**
 * The SiteHooks.mount of a corner's site: builds the two meshes into a THREE.LOD (drawn within CORNER_CULL u of the
 * camera: three's renderer updates a LOD as it projects it), registers the crowd groups and soft obstacles of the
 * windows on now, and re-reads the windows every WINDOW_POLL_MS. Returns the unmount.
 */
export function cornerMount(def: CornerDef): (group: THREE.Group, baseY: number) => () => void {
  return (group, baseY) => {
    const lod = new THREE.LOD();
    lod.name = `sf:${def.site}:corner`;
    const near = new THREE.Group(), far = new THREE.Object3D();
    // the LOD measures its distance from the corner's own middle (a corner may stand 40 u from its site's origin: the
    // Chinatown corner up Grant Ave from the Dragon Gate); the meshes keep the site's local frame
    const cx = (def.box[0] + def.box[2]) / 2, cz = (def.box[1] + def.box[3]) / 2;
    lod.position.set(cx, 0, cz);
    near.position.set(-cx, 0, -cz);
    lod.addLevel(near, 0);
    lod.addLevel(far, CORNER_CULL);
    group.add(lod);
    const st: CornerMounted = { def, active: new Set(), meshes: { toy: null, signs: null, triangles: 0, plaques: 0 }, lod, crowds: [], soft: [] };
    const offCrowds: (() => void)[] = [];
    const apply = (active: Set<string>) => {
      // meshes
      if (st.meshes.toy) near.remove(st.meshes.toy);
      if (st.meshes.signs) near.remove(st.meshes.signs);
      disposeMeshes(st.meshes);
      st.meshes = buildCornerMeshes(def, baseY, active);
      for (const m of [st.meshes.toy, st.meshes.signs]) if (m) { m.updateMatrix(); near.add(m); }
      near.updateMatrixWorld(true);
      // crowds
      for (const off of offCrowds.splice(0)) off();
      st.crowds = [];
      for (const c of def.crowds ?? []) {
        if (!on(c.when, active)) continue;
        const key = `corner:${def.id}:${c.key}`;
        const W = (p: Vec2) => cornerToWorld(def, p);
        const lane = c.lane ? (() => { const a = W({ x: c.lane!.ax, z: c.lane!.az }), b = W({ x: c.lane!.bx, z: c.lane!.bz }); return { ax: a.x, az: a.z, bx: b.x, bz: b.z }; })() : undefined;
        offCrowds.push(addCrowdSpots(key, c.spots.map(s => ({ ...W(s), r: s.r })), { face: c.face ? W(c.face) : undefined, count: c.count, lane }));
        st.crowds.push(key);
      }
      // soft obstacles
      st.soft = (def.soft ?? []).filter(s => on(s.when, active)).map(s => ({ ...cornerToWorld(def, s), r: s.r, kind: s.kind ?? 'static' }));
      st.active = active;
    };
    apply(activeWindows(def, bayParts(bayNow())));
    const offSoft = registerObstacleSource((out, x, z, r) => {
      for (const o of st.soft) { const d = r + o.r; if ((o.x - x) ** 2 + (o.z - z) ** 2 <= d * d) out.push(o); }
    });
    const same = (a: Set<string>, b: Set<string>) => a.size === b.size && [...a].every(k => b.has(k));
    const timer = def.windows ? setInterval(() => {
      const next = activeWindows(def, bayParts(bayNow()));
      if (!same(next, st.active)) apply(next);
    }, WINDOW_POLL_MS) : null;
    mounted.set(def.id, st);
    return () => {
      if (timer) clearInterval(timer);
      offSoft();
      for (const off of offCrowds.splice(0)) off();
      group.remove(lod);
      disposeMeshes(st.meshes);
      if (mounted.get(def.id) === st) mounted.delete(def.id);
    };
  };
}

