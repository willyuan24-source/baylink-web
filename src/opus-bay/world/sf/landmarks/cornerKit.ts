/** Local (x, z) of a corner's site → world (landmarks/index.ts landmarkToWorld, without importing the registry). */
export function cornerToWorld(def: CornerDef, p: Vec2): Vec2 {
  const c = Math.cos(def.frame.yaw), s = Math.sin(def.frame.yaw);
  return { x: def.frame.x + p.x * c + p.z * s, z: def.frame.z - p.x * s + p.z * c };
}

/** The windows on at Bay time `parts` (game/bayNow bayParts). */
export function activeWindows(def: CornerDef, parts: { hour: number; minute: number; weekday: number }): Set<string> {
  const out = new Set<string>();
  const m = parts.hour * 60 + parts.minute;
  for (const [id, w] of Object.entries(def.windows ?? {})) {
    if (w.days && !w.days.includes(parts.weekday)) continue;
    if (m >= w.from && m < w.to) out.add(id);
  }
  return out;
}

const on = (when: string | undefined, active: ReadonlySet<string>) => !when || active.has(when);

/** World ground height at a local point from the corner's baked grid (NaN without a grid). */
export function cornerGroundWorld(id: string, x: number, z: number): number {
  const g = CORNER_GROUND[id];
  if (!g) return NaN;
  const fx = Math.min(g.cols - 1, Math.max(0, (x - g.x0) / g.step)), fz = Math.min(g.rows - 1, Math.max(0, (z - g.z0) / g.step));
  const i = Math.min(g.cols - 2, Math.floor(fx)), j = Math.min(g.rows - 2, Math.floor(fz));
  const u = fx - i, v = fz - j, k = j * g.cols + i;
  const a = g.h[k] * (1 - u) + g.h[k + 1] * u, b = g.h[k + g.cols] * (1 - u) + g.h[k + g.cols + 1] * u;
  return (a * (1 - v) + b * v) / 100;
}

/** The corner's ground as local heights over `baseY` (its own grid; the site's when it gives one). */
export function cornerGround(def: CornerDef, baseY: number): CornerGround {
  if (def.ground) return def.ground;
  return { at: (x, z) => { const y = cornerGroundWorld(def.id, x, z); return Number.isFinite(y) ? y - baseY : 0; } };
}

