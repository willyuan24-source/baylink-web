/**
 * Wave 5 · lane L · the signature corners' kit (W5-L4 / W5-L5 / W5-L6, plan §3.6): the dressing a neighbourhood corner
 * adds to the site it stands in (Irving St, Clement St, 24th St, 3rd St, Haight, Japantown, Noe Valley, the Castro, and
 * Chinatown's Grant Ave from the Dragon Gate), drawn when that site's lod 0 is (world/sf/sites.ts SiteHooks.mount) and
 * only within CORNER_CULL u of the camera (measured from the corner's middle):
 *
 *   toy     ONE Mesh of the site's own TOY material: sign brackets, lanterns, a bus-stop seat row, a busker on his crate,
 *           market stalls … in the site's LOCAL frame (the same program as every site's lod 0: no new material)
 *   signs   ONE Mesh of lane V's signs atlas (world/sf/signsAtlas.ts SignBatch + signsMaterial, warmed as 'v-signs'):
 *           the painted bilingual plaques (generic trade words only, never a shop's name), flat on the boards or as
 *           double-sided blade signs over the sidewalk
 *   crowd   lane T's crowd spots (world/sf/crowdSpots.ts addCrowdSpots): the corner's "someone doing something" (an
 *           early queue, shoppers, listeners round a busker, neighbours at a stop), each in its Bay-time window
 *   soft    soft obstacles (actors/view registerObstacleSource) for what stands on the sidewalk only in a window (the
 *           busker, the Saturday stalls): the static walk data cannot switch with the clock
 *
 * Budget per corner (plan §4.8, tests/opus-bay-w5-corners.test.ts): ≤ 2 draw calls (the two meshes; no shadows cast),
 * ≤ 2.5k triangles, outer city only, no text meshes (the words are in the atlas texture). Bay-time windows are
 * re-read every WINDOW_POLL_MS while mounted (`?date=` in DEV / QA builds moves them); a change rebuilds the toy mesh and
 * the crowd groups. The corner's coin cache is lane E's (economy/coinSpots.ts COIN_CACHES, `cache`).
 *
 * Ground: `CornerGround.at(x, z)` = the local height over the site's base at a local point, from the corner's baked grid
 * (landmarks/cornerGround.ts, WORLD heights, generated by scripts/opus-sf/corners-ground.mts) minus the base the site
 * was mounted at (a 'terrain' landmark's base is only known then); a site's own grid can stand in (`ground`).
 */

/** a Bay-time window: minutes of the Bay day [from, to), on `days` (0 = Sunday; all days when absent) */
export interface CornerWindow { days?: readonly number[]; from: number; to: number }

/** one plaque of the signs atlas, LOCAL: centre, facing yaw `ry` (three.js), width `w` (height w / 2); `blade` = one face
 *  of a blade sign hung out over the sidewalk (else flat on a wall, a bay or a stall) */
export interface CornerSign { id: string; x: number; y: number; z: number; ry: number; w: number; blade?: true }

/** a crowd group (LOCAL coordinates; world/sf/crowdSpots.ts semantics), shown while its window is on */
export interface CornerCrowd {
  key: string;
  /** the window id (`windows`) it shows in; always when absent */
  when?: string;
  spots: { x: number; z: number; r?: number }[];
  face?: Vec2;
  count?: number;
  lane?: CrowdLane;
}

/** a soft obstacle (LOCAL) while its window is on: someone / something standing on the sidewalk for a while */
export interface CornerSoft { when?: string; x: number; z: number; r: number; kind?: 'static' | 'person' }

export interface CornerGround { at(x: number, z: number): number }

export interface CornerDef {
  /** corner id (`irving`, `clement`, `calle-24`, `third-street`, `haight`, `japantown`, `noe-valley`, `castro`) */
  id: string;
  /** the plan's row (§3.6 table: 1–4 must, 5–8) */
  order: number;
  /** the site (SF_SITES id) whose lod 0 carries the corner */
  site: string;
  /** the site's frame (a copy of its x, z, yaw: the corner's crowd and soft obstacles go to world space with it) */
  frame: { x: number; z: number; yaw: number };
  name: Bilingual;
  /** the ambient, in words (the report and the tests) */
  ambient: Bilingual;
  /** the local box (x0, z0, x1, z1) everything of the corner stays in; its ground is baked over it */
  box: readonly [number, number, number, number];
  windows?: Readonly<Record<string, CornerWindow>>;
  /** the site's own ground instead of the corner's baked grid (a shopping block whose boards the site draws) */
  ground?: CornerGround;
  /** the plaques (LOCAL) */
  signs(ground: CornerGround, on: ReadonlySet<string>): CornerSign[];
  /** the toy dressing (LOCAL, TOY conventions: aInfo.y local; the mount lifts it by the base) */
  build(b: BatchLike, ground: CornerGround, on: ReadonlySet<string>): void;
  crowds?: readonly CornerCrowd[];
  soft?: readonly CornerSoft[];
  /** lane E's cache id near the corner (economy/coinSpots.ts COIN_CACHES), null while E has none there */
  cache: string | null;
  /** the crowd's plaza additions of the corner (LOCAL polygons, already in the site's `plaza`: the tests check the spots) */
  plaza?: readonly Vec2[][];
  /**
   * `plaza` stays the corner's own (W5-L6): its crowd stands there, but the site's sightseers do not (they face the site:
   * Grant Ave's window shoppers stand 30–50 u up the street from the Dragon Gate). The tests check the spots the same way.
   */
  plazaOwn?: true;
}

/** the corner meshes stand only this close to the camera (u): their plaques are unreadable beyond, the site's lod 0 stays */
export const CORNER_CULL = 140;
/** Bay-time windows are re-read this often while a corner is mounted (ms) */
export const WINDOW_POLL_MS = 15_000;
/** budget per corner (plan §4.8) */
export const CORNER_BUDGET = { calls: 2, triangles: 2500 } as const;

