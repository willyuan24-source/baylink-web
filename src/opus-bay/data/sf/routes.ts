/**
 * The three finished walking routes of the city (lane D2, D2-11; plan sf-research-tech.md §7 "Finished routes gate
 * expansion", checkpoint §5.9): each one tied to BAYLINK content that exists (planner places and guides), with a named
 * place at least every 225 u of walking (≈ 30 s of running, gate G5) and a T1 / T2 landmark in view along the way.
 *
 *   R1  Chinatown → North Beach → Coit Tower      the Dragon Gate, Waverly Place, Portsmouth Square, Washington Square
 *   R2  Marina Green → the Golden Gate            the Palace, Crissy Field, Fort Point, the bridge's south tower
 *   R3  Golden Gate Park → Ocean Beach            the Conservatory, the de Young, Blue Heron Lake, the windmill
 *
 * DATA ONLY (no landmark library: GameRoot may import it). A stop's (x, z) is a walkable world spot on the route: a
 * landmark stop is its arrival (world/sf/landmarks/context.ts sfLandmarkAnchor, written out; the sf-routes test checks
 * them) — except Fort Point, whose arrival slot beside the bridge deck is boxed in (W5-L, the mid-wave checkpoint's
 * CP-8: its stop stands on Marine Drive's end loop in front of the fort, 7.9 u away, where every way is open) —, a place
 * stop its places.json point (or, for a big place such as the Polo Field, the walk's spot beside it, ≤ 20 u away; the
 * Tea Garden's is its gate, not the pond's middle), an attraction-only stop the attraction's arrival. Every stop passes
 * the walk sweep's judge (tests/opus-bay-w5-landmarks.test.ts). `placeId` = its places.json row
 * (lane G1's map, discovery, fast travel); `attraction` = its row in lane P's data/sf/attractions.ts when places.json has
 * none yet (the wave-4 extra places). Consumers: G1 (discovery / map lines), G2 (stop slots, lines), F (crowd).
 *
 * The walk itself (ROUTE_PATHS, generated by scripts/opus-sf/assets/routes-build.ts on the published walk graph) is the
 * A* route from stop to stop, simplified to 1 u; `stopAt` is each stop's arc position along it. Re-run the script after
 * changing a stop (the sf-routes test fails until you do). scripts/opus-sf/routes-qa.mjs walks the finished routes in the
 * app (D2-14).
 */

export type SfRouteId = 'r1' | 'r2' | 'r3';

export interface SfRouteStop {
  /** stable id within the city (`<route>-<slug>`) */
  id: string;
  name: Bilingual;
  /** landmark: a T1 / T2 landmark stop; place: a named place; filler: a smaller named place that keeps the gaps short */
  kind: 'landmark' | 'place' | 'filler';
  /** SF landmark registry id (world/sf/landmarks) for landmark stops, or the landmark a place stop belongs to */
  landmark?: string;
  /** places.json row (public/opus-bay/sf/v1/places.json) */
  placeId?: string;
  /** lane P's attraction id (data/sf/attractions.ts) */
  attraction?: string;
  /** world spot on the walk */
  x: number;
  z: number;
  /** one line for the stop (where you are, which way the walk goes) */
  line: Bilingual;
  /** unnamed waypoints (world x, z) the walk takes on its way TO this stop (the street the route means, e.g. Grant Ave) */
  via?: readonly (readonly [number, number])[];
}

export interface SfRoute {
  id: SfRouteId;
  name: Bilingual;
  blurb: Bilingual;
  /** BAYLINK: /planner-catalog.json place ids and /baybay-guides.json slugs this route belongs to */
  planner: readonly string[];
  guides: readonly string[];
  /** in walking order */
  stops: readonly SfRouteStop[];
}

