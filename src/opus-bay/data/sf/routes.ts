export function sfRoute(id: SfRouteId): SfRoute | undefined { return SF_ROUTES.find(r => r.id === id); }

/** A route's generated walk: the polyline (world x, z pairs), its length and each stop's arc position. */
export function routePath(id: SfRouteId): { points: readonly number[]; length: number; stopAt: readonly number[] } | undefined {
  return ROUTE_PATHS[id];
}

/** Walking distance between consecutive stops (u), from the generated walk. */
export function routeGaps(id: SfRouteId): number[] {
  const p = ROUTE_PATHS[id];
  if (!p) return [];
  return p.stopAt.slice(1).map((a, i) => Math.round((a - p.stopAt[i]) * 10) / 10);
}

/** The point and heading (world yaw of the walking direction) at arc position `s` along a route's walk. */
export function routePointAt(id: SfRouteId, s: number): { x: number; z: number; heading: number } | null {
  const p = ROUTE_PATHS[id];
  if (!p || p.points.length < 4) return null;
  const pts = p.points;
  let acc = 0;
  for (let k = 0; k + 3 < pts.length; k += 2) {
    const ax = pts[k], az = pts[k + 1], bx = pts[k + 2], bz = pts[k + 3], L = Math.hypot(bx - ax, bz - az);
    if (acc + L >= s || k + 4 >= pts.length) {
      const t = L > 0 ? Math.min(1, Math.max(0, (s - acc) / L)) : 0;
      return { x: ax + (bx - ax) * t, z: az + (bz - az) * t, heading: Math.atan2(bx - ax, bz - az) };
    }
    acc += L;
  }
  return null;
}
